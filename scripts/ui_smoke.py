"""Optional end-to-end UI check. Needs: pip install playwright && playwright install chromium, and the server running
(PELLIPLAN_DEMO=1 uvicorn app.main:app --port 8765). Walks the main flows and fails on any browser error."""
from playwright.sync_api import sync_playwright
errors = []
with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page(viewport={"width": 1180, "height": 900})
    pg.on("console", lambda m: errors.append(("console", m.text)) if m.type == "error" else None)
    pg.on("pageerror", lambda e: errors.append(("pageerror", str(e))))
    pg.goto("http://localhost:8765/")
    pg.click("text=Start the demo wedding"); pg.wait_for_selector("text=Hello, Sravya")
    pg.screenshot(path="/tmp/01_dashboard.png", full_page=True)
    pg.click("nav >> text=Plan"); pg.wait_for_selector("text=Buy bridal kanchi pattu saree")
    pg.click("text=Stitch bridal blouse"); pg.wait_for_selector("text=Days of work")
    pg.screenshot(path="/tmp/02_plan.png", full_page=True)
    pg.click("nav >> text=Dependencies"); pg.wait_for_selector("svg.graph")
    pg.screenshot(path="/tmp/03_graph.png", full_page=True)
    pg.click("nav >> text=What-if"); pg.wait_for_selector("text=Simulate")
    pg.click("button:has-text('Simulate')"); pg.wait_for_selector("text=Recovery plan")
    pg.screenshot(path="/tmp/04_whatif.png", full_page=True)
    pg.click("button:has-text('Show on the dependency graph')"); pg.wait_for_selector("svg.graph")
    pg.screenshot(path="/tmp/05_graph_highlight.png", full_page=True)
    pg.click("nav >> text=Wedding Brain"); pg.wait_for_selector("text=Ask about your plan")
    pg.click("button:has-text('muhurtham')"); pg.wait_for_selector("text=Muhurtham ·"); pg.wait_for_timeout(300)
    pg.set_input_files("input[type=file]", "samples/planning_notes.txt")
    pg.click("button:has-text('Analyse document')"); pg.wait_for_selector("text=Nothing here is in your plan yet")
    pg.screenshot(path="/tmp/06_brain.png", full_page=True)
    pg.select_option("#who-sel", label="Anusha (bridesmaid)"); pg.wait_for_selector("text=Hello, Anusha")
    pg.click("nav >> text=Plan"); pg.wait_for_selector("text=Blouse fitting")
    txt = pg.inner_text("main")
    print("bridesmaid sees private gift task:", "Surprise gift" in txt, "| sees rupee sign:", "\u20B9" in txt, "| What-if tab count:", pg.locator("nav >> text=What-if").count())
    pg.screenshot(path="/tmp/07_bridesmaid_plan.png", full_page=True)
    pg.select_option("#who-sel", label="Venkat Garu (family)"); pg.wait_for_selector("text=Hello, Venkat Garu")
    pg.screenshot(path="/tmp/08_family.png", full_page=True)
    m = b.new_page(viewport={"width": 390, "height": 800}); m.goto("http://localhost:8765/")
    m.evaluate("(t)=>{localStorage.setItem('pp_tokens',t);localStorage.setItem('pp_who','Sravya')}", pg.evaluate("localStorage.getItem('pp_tokens')"))
    m.reload(); m.wait_for_selector("text=Hello, Sravya"); m.screenshot(path="/tmp/09_mobile.png", full_page=True)
    b.close()
print("errors:", errors)
